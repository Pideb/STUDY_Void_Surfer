import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tracks, createSession } from './audio/compose-music.mjs';

const root = new URL('../', import.meta.url);
const output = new URL('public/assets/audio/', root);
const approvedBoss = JSON.parse(await readFile(new URL('.memory/previews/2026-10-27-stage-boss-bgm/samples.json', root), 'utf8'));
const hash = (value) => createHash('sha256').update(value).digest('hex');
const manifest = {};
await mkdir(new URL('gameplay/', output), { recursive: true });
await mkdir(new URL('boss/', output), { recursive: true });
for (const [index, base] of tracks.entries()) {
  manifest[base.id] = {};
  for (const mode of ['gameplay', 'boss']) {
    const boss = mode === 'boss';
    const score = boss ? approvedBoss.find((entry) => entry.id === base.id) : base;
    const seed = (boss ? 3700 : 2700) + index;
    const previewFolder = boss ? 'stage-boss-bgm' : 'stage-bgm';
    const preview = await readFile(new URL(`.memory/previews/2026-10-27-${previewFolder}/${base.id}.wav`, root));
    if (hash(createSession(score, seed).bytes) !== hash(preview)) throw new Error(`Approved preview changed: ${mode}/${base.id}`);
    const { bytes, metadata } = createSession({ ...score, loop: true }, seed);
    await writeFile(new URL(`${mode}/${base.id}.wav`, output), bytes);
    manifest[base.id][mode] = {
      url: `/assets/audio/${mode}/${base.id}.wav`, title: score.title,
      bpm: score.bpm, durationSeconds: metadata.durationSeconds, bars: metadata.bars,
      sampleRate: metadata.sampleRate, channels: metadata.channels,
    };
    console.log(`${mode}/${base.id}: ${metadata.bars} bars / ${metadata.durationSeconds.toFixed(3)}s loop`);
  }
}
await copyFile(new URL('.memory/previews/2026-10-27-boss-entry-siren/01-sweep.wav', root), new URL('boss-entry.wav', output));
await writeFile(new URL('manifest.json', output), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(new URL('src/audio/music-manifest.js', root), `// Generated by node scripts/build-game-audio.mjs.\nexport const MUSIC_TRACKS = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`);
// Reappend the independent menu entry after regenerating the six stage pairs.
await import('./build-menu-audio.mjs');
