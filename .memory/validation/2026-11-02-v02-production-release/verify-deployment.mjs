import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const dir='.memory/validation/2026-11-02-v02-production-release';
const head=process.argv[2]||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
const registry=JSON.parse(fs.readFileSync('docs/management/releases.json','utf8'));
const origin='https://proud-grass-03a132e00.6.azurestaticapps.net';
const api=await fetch('https://api.github.com/repos/Pideb/STUDY_Void_Surfer/actions/runs?branch=main&event=push&per_page=10',{headers:{'User-Agent':'void-surfer-release'}});
assert.equal(api.status,200);const runs=await api.json();
const run=runs.workflow_runs.find(run=>run.head_sha===head);assert.ok(run,'Exact pushed HEAD run required');
assert.equal(run.status,'completed');assert.equal(run.conclusion,'success');
const read=async url=>{const r=await fetch(url,{headers:{'Cache-Control':'no-cache'}});assert.equal(r.status,200,url);return Buffer.from(await r.arrayBuffer());};
const index=await read(origin+'/?release-check='+head);
const script=index.toString().match(/<script[^>]+src="([^"]+\.js)"/)[1];
const localIndex=fs.readFileSync('dist/index.html','utf8');assert.ok(localIndex.includes(script),'Production script must match current local build');
const bundle=await read(new URL(script,origin)),local=fs.readFileSync(path.join('dist',script));
const sha=data=>crypto.createHash('sha256').update(data).digest('hex');assert.equal(sha(bundle),sha(local));
const guide=(await read(origin+'/guide/index.html?release-check='+head)).toString();
assert.equal(guide.replace(/\r\n/g,'\n'),fs.readFileSync('public/guide/index.html','utf8').replace(/\r\n/g,'\n'));
assert.match(guide,/<h3 class="update-version">v0\.2<\/h3>/);assert.match(guide,/font-weight:800/);
const proof={version:registry.currentVersion,gameFingerprint:registry.gameFingerprint,headSha:head,runId:run.id,runUrl:run.html_url,conclusion:run.conclusion,completedAtUtc:run.updated_at,bundleSha256:sha(bundle),origin};
const suffix=process.argv[3]||'deployment';
fs.writeFileSync(dir+'/'+suffix+'-proof.json',JSON.stringify(proof,null,2)+'\n');
fs.writeFileSync(dir+'/'+suffix+'-verification.json',JSON.stringify({checkedAtUtc:new Date().toISOString(),headSha:head,script,localSha256:sha(local),productionSha256:sha(bundle),guideExactMatch:true,run:{id:run.id,status:run.status,conclusion:run.conclusion,head_sha:run.head_sha,html_url:run.html_url}},null,2)+'\n');
console.log(JSON.stringify(proof));
